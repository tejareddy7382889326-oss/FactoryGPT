import os
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_pdf_report(
    output_path: str,
    title: str,
    equipment_name: str,
    report_type: str,
    notes: str,
    conversation_history: list = None
):
    """
    Generates an enterprise industrial maintenance / troubleshooting PDF report.
    """
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )
    
    styles = getSampleStyleSheet()
    
    # Custom Industrial Styling
    primary_color = colors.HexColor("#0F172A") # Slate 900
    accent_color = colors.HexColor("#0284C7")  # Cyan 600
    text_color = colors.HexColor("#334155")    # Slate 700
    bg_light = colors.HexColor("#F8FAFC")      # Slate 50
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=primary_color,
        spaceAfter=10
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=accent_color,
        spaceAfter=15
    )
    
    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['BodyText'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=text_color,
        spaceAfter=8
    )

    header_meta_style = ParagraphStyle(
        'DocMeta',
        parent=styles['BodyText'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#64748B")
    )
    
    elements = []
    
    # Header Banner
    elements.append(Paragraph("FactoryGPT Industrial AI Assistant", header_meta_style))
    elements.append(Paragraph(f"REPORT: {title.upper()}", title_style))
    elements.append(HRFlowable(width="100%", thickness=2, color=accent_color, spaceAfter=15))
    
    # Metadata Table
    data = [
        [
            Paragraph("<b>Equipment / Machine:</b>", body_style), Paragraph(equipment_name, body_style),
            Paragraph("<b>Report Type:</b>", body_style), Paragraph(report_type.capitalize(), body_style)
        ],
        [
            Paragraph("<b>Generated Date:</b>", body_style), Paragraph(datetime.now().strftime("%Y-%m-%d %H:%M:%S"), body_style),
            Paragraph("<b>Generated By:</b>", body_style), Paragraph("FactoryGPT System", body_style)
        ]
    ]
    meta_table = Table(data, colWidths=[120, 150, 100, 150])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), bg_light),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#E2E8F0")),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E1")),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 15))
    
    # Technician Notes Section
    if notes:
        elements.append(Paragraph("Technician / Operating Notes", subtitle_style))
        elements.append(Paragraph(notes.replace("\n", "<br/>"), body_style))
        elements.append(Spacer(1, 15))
        
    # AI Diagnosis & Maintenance History
    if conversation_history:
        elements.append(Paragraph("AI Diagnosis & Troubleshooting Transcript", subtitle_style))
        for msg in conversation_history:
            role_prefix = "<b>USER QUERY:</b>" if msg.get("role") == "user" else "<b>AI MAINTENANCE DIAGNOSIS:</b>"
            content_text = msg.get("content", "").replace("\n", "<br/>")
            
            box_bg = colors.HexColor("#F1F5F9") if msg.get("role") == "user" else colors.HexColor("#EFF6FF")
            border_c = colors.HexColor("#CBD5E1") if msg.get("role") == "user" else colors.HexColor("#93C5FD")
            
            msg_table = Table([[
                Paragraph(f"{role_prefix}<br/>{content_text}", body_style)
            ]], colWidths=[520])
            msg_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (0,0), box_bg),
                ('BOX', (0,0), (0,0), 1, border_c),
                ('PADDING', (0,0), (0,0), 8),
            ]))
            elements.append(msg_table)
            elements.append(Spacer(1, 10))

            # Citations list if present
            if msg.get("sources"):
                citations_text = "<b>Retrieved Citations & Documents:</b><br/>"
                for src in msg.get("sources"):
                    doc_n = src.get("document_name", "Unknown Document")
                    page = src.get("page", 1)
                    citations_text += f"• <i>{doc_n}</i> (Page {page})<br/>"
                
                cite_table = Table([[
                    Paragraph(citations_text, ParagraphStyle('CiteText', parent=body_style, fontSize=8, leading=11, textColor=colors.HexColor("#475569")))
                ]], colWidths=[520])
                cite_table.setStyle(TableStyle([
                    ('BACKGROUND', (0,0), (0,0), colors.HexColor("#F8FAFC")),
                    ('BOX', (0,0), (0,0), 0.5, colors.HexColor("#E2E8F0")),
                    ('PADDING', (0,0), (0,0), 6),
                ]))
                elements.append(cite_table)
                elements.append(Spacer(1, 10))
                
    # Footer Sign-off
    elements.append(Spacer(1, 20))
    elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceAfter=10))
    sign_table = Table([
        [Paragraph("<b>Technician Signature:</b> ___________________", body_style), Paragraph("<b>Supervisor Approval:</b> ___________________", body_style)]
    ], colWidths=[260, 260])
    elements.append(sign_table)

    doc.build(elements)
    return output_path
